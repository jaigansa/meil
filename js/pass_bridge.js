/**
 * pass_bridge.js - Unix pass CLI Generator & Integration
 * Formats password vault entries into standard pass CLI directory structure
 * and exports an executable bash script (pass_import.sh).
 */

class PassBridge {
  constructor() {
    this.setupEventListeners();
  }

  setupEventListeners() {
    const btnExportPass = document.getElementById('btn-export-pass-script');
    if (btnExportPass) {
      btnExportPass.addEventListener('click', () => {
        this.downloadPassImportScript();
      });
    }

    const btnInfo = document.getElementById('btn-pass-info');
    if (btnInfo) {
      btnInfo.addEventListener('click', () => {
        alert(
          '=== HOW TO USE WITH UNIX PASS CLI ===\n\n' +
          '1. In Linux/macOS terminal, run:\n' +
          '   chmod +x pass_import.sh && ./pass_import.sh\n\n' +
          '2. To sync with your GitHub repo via pass CLI:\n' +
          '   pass git push origin main || pass git push origin master\n\n' +
          '3. Any password stored here can be viewed via:\n' +
          '   pass show <path>\n' +
          '   pass -c <path>  (copies password directly to clipboard)'
        );
      });
    }
  }

  generateBashScript() {
    const passwords = window.storage ? window.storage.getPasswords() : [];
    const reminders = window.storage ? window.storage.getReminders() : [];

    let script = `#!/usr/bin/env bash
# ==============================================================================
# pass_import.sh - Generated by MEIL TUI Vault
# Imports passwords and active memories into Unix pass CLI (~/.password-store)
# ==============================================================================
set -euo pipefail

command -v pass >/dev/null 2>&1 || { echo "[ERROR] 'pass' is not installed. Aborting." >&2; exit 1; }

echo "[INFO] Importing entries into password-store..."
`;

    // Process Passwords
    passwords.forEach(p => {
      // Clean path: strip leading slashes and dangerous shell chars
      const safePath = (p.path || 'general/untitled')
        .replace(/^\/+/, '')
        .replace(/[^a-zA-Z0-9_\-\.\/]/g, '_');

      const passVal = p.password || '';
      const userVal = p.username ? `username: ${p.username}` : '';
      const notesVal = p.notes ? `notes: ${p.notes.replace(/\n/g, ' ')}` : '';

      script += `
echo "-> Inserting pass: ${safePath}"
pass insert -m -f "${safePath}" << 'EOF_SECRET'
${passVal}
${userVal}
${notesVal}
EOF_SECRET
`;
    });

    // Optionally process Reminders as memory notes
    if (reminders.length > 0) {
      script += `\necho "[INFO] Importing active reminders into memories/ folder..."\n`;
      reminders.forEach(r => {
        const safeTitle = (r.title || 'untitled')
          .toLowerCase()
          .replace(/[^a-zA-Z0-9_\-]/g, '-')
          .slice(0, 40);
        const memPath = `memories/${r.date || 'general'}/${safeTitle}`;

        script += `
echo "-> Inserting memory: ${memPath}"
pass insert -m -f "${memPath}" << 'EOF_MEM'
${r.title}
date: ${r.date} ${r.time}
repeat: ${r.repeat}
priority: ${r.priority}
details: ${r.details || ''}
EOF_MEM
`;
      });
    }

    script += `
echo ""
echo "[SUCCESS] Import completed! Total entries imported."
echo "If your password-store is a git repository, push changes now:"
echo "    pass git push origin main || pass git push origin master"
`;

    return script;
  }

  downloadPassImportScript() {
    const script = this.generateBashScript();
    const blob = new Blob([script], { type: 'text/x-shellscript' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'pass_import.sh';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    if (window.audio) window.audio.playSuccess();
    alert('OK: Generated "pass_import.sh" downloaded. Run in terminal with `./pass_import.sh` to import into pass CLI.');
  }
}

window.passBridge = new PassBridge();
